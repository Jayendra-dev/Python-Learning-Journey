#Ask the user for a temperature in Celsius (string input). Convert it to float ,
#then calculate and print temperature in Fahrenheit.
# Conversion formula: Fahrenheit Temp = (CelsiusTemp ∗ (9/5)) +32


celsius_temp=float(input("enter in temperature in celsius:"))
fahrenheit_temp=(celsius_temp*(9/5)+32)
print("temperature in fahrenheit:",fahrenheit_temp)


